def double(x):
    return 2 * x


def triple(x):
    return 3 * x


def carre(x):
    return x * x


def oppose(x):
    return -x


def moitie(x):
    return x / 2


def moyenne(valeurs):
    return sum(valeurs) // len(valeurs)


def maximum(valeurs):
    return max(valeurs)


def minimum(valeurs):
    return min(valeurs)
